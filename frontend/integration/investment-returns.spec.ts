  expect(Number(corrected.amounts.totalProfit)).toBe(330);
  expect(corrected.xirr.rate).not.toBe(sold.xirr.rate);
  await page.goto('/investments/performance');
  await page.getByLabel('统计开始日期', { exact: true }).fill('2025-01-01');
  await page.getByLabel('统计结束日期', { exact: true }).fill('2026-01-01');
  await page.getByRole('combobox', { name: '资产', exact: true }).press('ArrowDown');
  await page.locator('.ant-select-item-option-content').filter({ hasText: '收益率浏览器验收资产' }).click();
  for (const width of [1440, 360]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect(page.getByText(`${(corrected.xirr.rate * 100).toFixed(2)}%`, { exact: true })).toBeVisible();
    await expect(page.getByRole('img', { name: '现金流图：投入为负，回收为正，边界估值为计算项，缺失金额留空。精确金额请查看计算明细。' })).toBeVisible();
    await page.getByRole('button', { name: '查看计算现金流', exact: true }).click();
    const detail = page.getByRole('dialog', { name: '收益率计算详情' });
    await expect(detail.getByText('ClosingValue', { exact: true })).toBeVisible();
    await detail.getByRole('button', { name: '关闭', exact: true }).click();
    const pending = page.waitForEvent('download');
    await page.getByRole('button', { name: '导出计算明细 JSON', exact: true }).click();
    const download = await pending;
    const stream = await download.createReadStream();
    expect(stream).toBeTruthy();
    let content = ''; for await (const chunk of stream!) content += chunk.toString();
    const exported = JSON.parse(content);
    expect(exported.id).toBe(asset.id);
    expect(exported.cashFlows.length).toBe(corrected.cashFlows.length);
    expect(Number(exported.amounts.totalProfit)).toBe(330);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy();
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('combobox', { name: 'XIRR 报告币种', exact: true }).press('ArrowDown');
  await page.locator('.ant-select-item-option-content').filter({ hasText: /^USD$/ }).click();
  await expect(page.getByText('缺少现金流日期的直接历史汇率', { exact: true })).toBeVisible();
  for (const date of ['2025-01-01', '2025-08-01', '2025-09-01', '2025-10-01', '2026-01-01']) {
    await write('/fx-valuation-rates', { baseCurrency: 'CNY', targetCurrency: 'USD', rate: date === '2026-01-01' ? '0.2' : '0.1', date, source: 'Isolated E2E historical FX' });
  }
  const converted = await get(resultPath.replace('currency=CNY', 'currency=USD'));
  expect(converted.xirr.status).toBe('Success');
  expect(Number(converted.amounts.reportTotalProfit)).toBe(165);
  await page.getByRole('button', { name: /刷\s*新/ }).click();
  await expect(page.getByText(`${(converted.xirr.rate * 100).toFixed(2)}%`, { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '切换主题', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('combobox', { name: 'Language / 语言', exact: true }).press('ArrowDown');
  await page.locator('.ant-select-item-option-content').filter({ hasText: /^English$/ }).click();
  for (const width of [1440, 360]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect(page.getByText('Asset XIRR (annualized)', { exact: true })).toBeVisible();
    await expect(page.getByText(`${(converted.xirr.rate * 100).toFixed(2)}%`, { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'View calculation cash flows', exact: true }).click();
    const detail = page.getByRole('dialog', { name: 'Return calculation details' });
    await expect(detail.getByText(/Isolated E2E historical FX/).first()).toBeVisible();
    await detail.getByRole('button', { name: 'Close', exact: true }).click();
    const pending = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export calculation details JSON', exact: true }).click();
    const stream = await (await pending).createReadStream();
    let content = ''; for await (const chunk of stream!) content += chunk.toString();
    const exported = JSON.parse(content);
    expect(exported.currency).toBe('USD');
    expect(exported.originalCurrency).toBe('CNY');
    expect(Number(exported.amounts.reportTotalProfit)).toBe(165);
    expect(exported.amounts.exchangeAttribution.status).toBe('Success');
    expect(Number(exported.amounts.exchangeAttribution.localProfitAtClosingRate)).toBe(66);
    expect(Number(exported.amounts.exchangeAttribution.cashFlowFxTimingImpact)).toBe(99);
    expect(exported.cashFlows.every((flow: { rateSource: string }) => flow.rateSource === 'Isolated E2E historical FX')).toBeTruthy();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy();
  }
  expect(errors).toEqual([]);
  await page.setViewportSize({ width: 1440, height: 1000 });
  const compare = page.getByRole('region', { name: 'Investment asset comparison', exact: true });
  const project=await write('/directory/projects',{name:'Explicit investment project',currency:'CNY',budget:'0'});
  await page.getByRole('button',{name:'Record project classification',exact:true}).click();
  const projectDialog=page.getByRole('dialog',{name:'Record project classification',exact:true});
  await projectDialog.getByLabel('Project (leave empty to unassign)',{exact:true}).press('ArrowDown');
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').filter({hasText:'Explicit investment project'}).click();
  await projectDialog.getByLabel('Effective date',{exact:true}).fill('2025-06-01');await projectDialog.getByLabel('Classification source',{exact:true}).fill('Explicit whole-asset research project');
  await projectDialog.getByText('I confirm whole-asset classification',{exact:true}).click();await projectDialog.getByRole('button',{name:'OK',exact:true}).click();await expect(projectDialog).not.toBeVisible();
  expect((await get(`/investments/assets/${asset.id}/project?date=2026-01-01`)).projectId).toBe(project.id);
  await compare.getByRole('combobox', { name: 'Select comparison assets' }).press('ArrowDown');
  await page.locator('.ant-select-item-option-content').filter({ hasText: '收益率浏览器验收资产' }).click();
  await compare.getByText('Investment asset comparison', { exact: true }).click();
  await compare.getByRole('button', { name: 'Compare returns', exact: true }).click();
  await expect(compare.getByRole('cell', { name: `${(converted.xirr.rate * 100).toFixed(2)}%`, exact: true })).toBeVisible();
  await expect(compare.getByRole('cell', { name: 'Available', exact: true })).toBeVisible();
  await expect(compare.getByRole('cell',{name:'Explicit investment project',exact:true})).toBeVisible();
  await page.goto('/reports/custom');
  await page.getByLabel('Data topic', { exact: true }).press('ArrowDown');
  await page.locator('.ant-select-item-option-content').filter({ hasText: 'Investment cash-flow returns (up to 20 assets)' }).click();
  await page.getByLabel('Start date', { exact: true }).fill('2025-01-01');
  await page.getByLabel('End date', { exact: true }).fill('2026-01-01');
  await page.getByRole('button', { name: 'Preview report', exact: true }).click();
  await expect(page.getByRole('cell', { name: `${(corrected.xirr.rate * 100).toFixed(2)}%`, exact: true })).toBeVisible();
  const definition = { name: 'Isolated return report', theme: 'InvestmentReturns', start: '2025-01-01', end: '2026-01-01', currency: 'USD', metrics: ['xirrPercent', 'totalProfit'] };
  const report = await get(resultPath.replace('currency=CNY', 'currency=USD'));
  for (const format of ['CSV', 'Excel']) {
    const job = await write('/reports/custom/export', { definition, format });
    const file = await page.request.get(job.downloadUrl, { headers });
    expect(file.ok()).toBeTruthy();
    if (format === 'CSV') {
      const csv = await file.text();
      expect(csv).toContain('xirrPercent'); expect(csv).toContain('totalProfit');
      expect(csv).toContain(String(report.xirr.rate * 100));
      expect(csv).toContain('165');
    } else expect((await file.body()).subarray(0, 2).toString()).toBe('PK');
  }
  expect(errors).toEqual([]);
  console.log('Investment real API E2E: 1 asset, 4 active trades, 1 revoked trade, 1 valuation, 5 historical FX quotes; viewports 1440/360; Chinese light and English dark; missing FX and converted JSON verified');
  // Confirm full cash+holdings account values; internal security trades are not external capital.
  const second=await write('/accounts',{name:'收益率组合第二账户',type:'Investment',currency:'CNY',openingBalance:'0'});
  await write('/transactions/transfer',{type:'Transfer',amount:'100',accountId:account.id,toAccountId:second.id,occurredAt:'2025-11-01T10:00:00+08:00',note:'隔离组合内部调拨'});
  for(const [accountId,date,value] of [[account.id,'2024-12-31','10000'],[account.id,'2026-01-01','10230'],[second.id,'2024-12-31','0'],[second.id,'2026-01-01','100']])await write('/investments/boundary-values',{accountId,date,value,source:'Cash ledger plus all holdings, isolated verification',includesCashAndHoldings:true});
  const portfolio=await write('/investments/returns/boundary',{accountIds:[account.id,second.id],start:'2025-01-01',end:'2026-01-01',currency:'CNY'});
  expect(portfolio.xirr.status).toBe('Success');expect(portfolio.xirr.rate).toBeCloseTo(.033,8);expect(Number(portfolio.totalProfit)).toBe(330);
  expect(portfolio.cashFlows.length).toBe(2);
  await page.goto(`/investments/performance?assetId=${asset.id}&currency=CNY`);
  await page.getByLabel('Statistics start date',{exact:true}).fill('2025-01-01');await page.getByLabel('Statistics end date',{exact:true}).fill('2026-01-01');
  await page.getByRole('button',{name:'Load historical trend',exact:true}).click();
  await expect(page.getByText('Historical value and returns',{exact:true})).toBeVisible();
  const boundary=page.getByRole('region',{name:'Account and portfolio returns'});
  await boundary.getByRole('combobox',{name:'Return calculation accounts'}).press('ArrowDown');
  for(const name of ['收益率隔离投资账户','收益率组合第二账户'])await page.locator('.ant-select-item-option-content').filter({hasText:name}).click();
  await boundary.getByText('Account and portfolio returns',{exact:true}).click();await boundary.getByRole('button',{name:'Calculate account or portfolio XIRR'}).click();
  await expect(boundary.getByText('3.30% · Annualized XIRR',{exact:true})).toBeVisible();
  await boundary.getByRole('button',{name:'Record full account value',exact:true}).click();
  const valueDialog=page.getByRole('dialog',{name:'Record full account value',exact:true});
  await valueDialog.getByLabel('Investment account',{exact:true}).press('ArrowDown');
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').filter({hasText:'收益率隔离投资账户'}).click();
  await valueDialog.getByLabel('Valuation date',{exact:true}).fill('2026-01-01');
  await valueDialog.getByLabel('Full account value in original currency',{exact:true}).fill('10230');
  await valueDialog.getByLabel('Verification source',{exact:true}).fill('UI verified full cash and holdings');
  await valueDialog.getByText('I verified cash and all holdings without double counting',{exact:true}).click();
  await valueDialog.getByRole('button',{name:'OK',exact:true}).click();await expect(valueDialog).not.toBeVisible();
  await expect(boundary.getByText('3.30% · Annualized XIRR',{exact:true})).toBeVisible();
  const annual=await get('/reports/center/data?mode=annual&period=2025&currency=CNY');expect(annual.investmentReturns).toBeTruthy();expect(annual.investmentReturns.items[0].xirr.status).toBe('ValuationMissing');
  await page.goto('/assets/allocation');
  for(const width of [1440,360]){await page.setViewportSize({width,height:1000});await expect(page.getByRole('region',{name:'Investment asset comparison',exact:true})).toBeVisible();expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBeTruthy();}
  expect(errors).toEqual([]);
